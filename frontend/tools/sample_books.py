"""Sample real Stake Math SDK books for the local demo and the mock RGS.

usage: python3 tools/sample_books.py PUBLISH_DIR OUT_DIR
Draws books by lookup-table weight (so the demo feels like the real game) and adds
tagged extras (bonus, pause, rewind, big, cap) that the dev panel and mock can force.
Also writes src/js/mathdata.js: cost, RTP and max win per mode from the lookup tables.
"""
import io, json, os, random, sys, csv
import zstandard

PUB, OUT = sys.argv[1], sys.argv[2]
N = {"base": 600, "ante": 400, "bonus": 40, "double": 30, "director": 25}
random.seed(1989)
index = json.load(open(os.path.join(PUB, "index.json")))
mathdata = {}

def tags_of(b):
    t = set(); ev = b["events"]; types = [e["type"] for e in ev]
    if "freeSpinTrigger" in types: t.add("bonus")
    if any(e["type"] == "pauseRespin" and e["win"] > 0 for e in ev): t.add("pause")
    if "rewind" in types: t.add("rewind")
    pm = b["payoutMultiplier"] / 100
    if pm >= 20: t.add("big")
    if pm >= 100: t.add("epic")
    if "wincap" in types: t.add("cap")
    if pm == 0: t.add("zero")
    if 0 < pm < 20 and "freeSpinTrigger" not in types: t.add("win")
    if any(a > 0 for e in ev if e["type"] == "reveal" for a in e.get("anticipation", [])): t.add("anticipation")
    return sorted(t)

for m in index["modes"]:
    name, cost = m["name"], m["cost"]
    ids, w, pays = [], [], {}
    for row in csv.reader(open(os.path.join(PUB, m["weights"]))):
        i, wt, p = int(row[0]), int(row[1]), int(row[2])
        ids.append(i); w.append(wt); pays[i] = p
    tw = sum(w)
    rtp = sum(wt * pays[i] / 100 for i, wt in zip(ids, w)) / tw / cost
    mathdata[name] = {"cost": cost, "rtp": round(rtp * 100, 2), "maxWin": max(pays.values()) / 100}
    pick = set(random.choices(ids, weights=w, k=N[name]))
    want_extra = {"bonus": 8, "pause": 6, "rewind": 6, "big": 6, "epic": 3, "cap": 1, "anticipation": 4}
    got = {k: 0 for k in want_extra}
    keep = {}
    r = io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(open(os.path.join(PUB, m["events"]), "rb")), encoding="utf-8")
    for line in r:
        b = json.loads(line)
        tg = tags_of(b)
        take = b["id"] in pick
        for k in tg:
            if k in got and got[k] < want_extra[k] and (k != "cap" or len(line) < 400_000):
                got[k] += 1; take = True
        if take:
            keep[b["id"]] = {"id": b["id"], "payoutMultiplier": b["payoutMultiplier"], "tags": tg, "drawn": b["id"] in pick, "events": b["events"]}
        if len(keep) >= len(pick) and all(got[k] >= want_extra[k] for k in got):
            break
    rows = sorted(keep.values(), key=lambda x: x["id"])
    with open(os.path.join(OUT, f"books_{name}.json"), "w") as f:
        json.dump(rows, f, separators=(",", ":"))
    print(name, len(rows), got, os.path.getsize(os.path.join(OUT, f"books_{name}.json")) // 1024, "KB")

js = os.path.join(os.path.dirname(OUT.rstrip("/")), "js", "mathdata.js")
with open(js, "w") as f:
    f.write("// generated by tools/sample_books.py from math/publish lookup tables\n")
    f.write("window.MATHDATA=" + json.dumps(mathdata, separators=(",", ":")) + ";\n")
print(mathdata)
